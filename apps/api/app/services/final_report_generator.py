def _coerce_uuid(value: Any) -> uuid.UUID | None:
    """Best-effort str/UUID → UUID. Unparsable ⇒ None (never fabricate/raise)."""
    if value is None:
        return None
    if isinstance(value, uuid.UUID):
        return value
    try:
        return uuid.UUID(str(value))
    except (ValueError, TypeError, AttributeError):
        return None


def _evidence_content_hash(item: PersistableEvidence, canonical_url: str | None) -> str:
    """Deterministic 64-char content_hash for one evidence item's canonical source.

    SEC/XBRL statement facts carry ``url=None``, so the hash keys on the
    query-stripped canonical URL + source_type + content_tier + a hash of the
    excerpt + period/date + the supported field set. Two runs of the same company
    produce the same key ⇒ ``get_or_create_source`` dedups; genuinely different
    statements (income vs cash-flow) differ by ``fields_supported`` ⇒ distinct
    sources. Never encodes a secret (the URL was already secret-stripped +
    canonicalised).
    """
    excerpt = (item.excerpt or "").strip().lower()
    excerpt_hash = (
        hashlib.sha256(excerpt.encode("utf-8")).hexdigest()[:16] if excerpt else ""
    )
    period = ""
    if isinstance(item.primary_fact, dict):
        period = str(item.primary_fact.get("period") or "")
    key = "|".join(
        [
            (canonical_url or "").split("?")[0],
            item.source_type or "",
            item.content_tier or item.source_tier or "",
            excerpt_hash,
            period or (item.date or ""),
            ",".join(sorted(item.fields_supported or [])),
        ]
    )
    return hashlib.sha256(key.encode("utf-8")).hexdigest()


def _is_deep_primary_document(item: PersistableEvidence) -> bool:
    """True when this item was DEEP-ingested from a primary document (Slice 5).

    Signalled by the raw-bytes ``document_content_hash`` the deep extractor stamps
    on each excerpt / validated-fact item (present ONLY when the master ingestion
    flag is on). Shallow (29B.2) / metadata-only / non-document items carry None.
    """
    return bool(getattr(item, "document_content_hash", None))


def _source_content_hash(item: PersistableEvidence, canonical_url: str | None) -> str:
    """The canonical Source ``content_hash`` for one evidence item.

    Phase 32A Slice 5 (C4): a DEEP-ingested primary-document item is keyed by its
    RAW-bytes document hash, so every excerpt / fact from the SAME document dedups
    to ONE canonical Source (one source per distinct document) and a re-run never
    accumulates duplicate document sources. The existing SHALLOW path keeps the
    synthesized url+tier+excerpt hash unchanged ⇒ the dark path is byte-identical.
    """
    if _is_deep_primary_document(item):
        return str(item.document_content_hash)
    return _evidence_content_hash(item, canonical_url)


# Provenance markers the deep extractor stamps into ``EvidenceItem.provenance`` as
# ``key=value`` strings (see ``company_ir._artifact_to_evidence``). Parsed back into
# a structured citation-provenance dict at persist/report time (never a secret).
_PROV_PAGE = "page="
_PROV_SECTION = "section="
_PROV_TABLE = "table="
_PROV_METHOD = "method="
_PROV_CONFIDENCE = "confidence="
_OCR_METHODS = frozenset({"ocr", "ocr_pdf", "ocr_image"})


def _primary_document_provenance(
    item: PersistableEvidence,
) -> dict[str, Any] | None:
    """Structured page/section/table provenance for a DEEP primary-document item.

    Returns ``None`` for any non-deep item (so only genuinely extracted primary
    documents surface page/section into the citation representation). For a deep
    item, parses the deterministic ``key=value`` provenance markers into
    ``{page_number, section, table_location, extraction_method, confidence,
    document_content_hash}`` and falls back to the structured ``primary_fact``
    page for validated facts. An OCR extraction_method adds an honest
    ``ocr_disclosure`` (fields present even though OCR is a NoOp this slice).
    Carries no raw document text — only bounded provenance metadata.
    """
    if not _is_deep_primary_document(item):
        return None
    page_number: int | None = None
    section: str | None = None
    table_location: str | None = None
    extraction_method: str | None = None
    confidence: float | None = None
    for entry in item.provenance or []:
        text = str(entry)
        if text.startswith(_PROV_PAGE):
            raw = text[len(_PROV_PAGE):].strip()
            if raw.isdigit():
                page_number = int(raw)
        elif text.startswith(_PROV_SECTION):
            section = text[len(_PROV_SECTION):].strip() or None
        elif text.startswith(_PROV_TABLE):
            table_location = text[len(_PROV_TABLE):].strip() or None
        elif text.startswith(_PROV_METHOD):
            extraction_method = text[len(_PROV_METHOD):].strip() or None
        elif text.startswith(_PROV_CONFIDENCE):
            raw = text[len(_PROV_CONFIDENCE):].strip()
            try:
                confidence = float(raw)
            except ValueError:
                confidence = None
    # Structured fact fallback: a validated fact carries its page + table location
    # on ``primary_fact`` even when the provenance string is absent.
    pf = item.primary_fact if isinstance(item.primary_fact, dict) else None
    if pf is not None:
        if page_number is None and isinstance(pf.get("page_number"), int):
            page_number = pf["page_number"]
        if table_location is None and pf.get("excerpt_id"):
            table_location = str(pf["excerpt_id"])
    prov: dict[str, Any] = {
        "page_number": page_number,
        "section": section,
        "table_location": table_location,
        "extraction_method": extraction_method,
        "confidence": confidence,
        "document_content_hash": str(item.document_content_hash),
    }
    if (extraction_method or "").lower() in _OCR_METHODS:
        prov["ocr_disclosure"] = (
            "OCR-derived text (optical character recognition) — accuracy is "
            "unverified; human review required."
        )
    return prov


def _is_metadata_only(item: PersistableEvidence) -> bool:
    return (item.data_quality or "") in _METADATA_ONLY_QUALITIES


def _is_financial_fact(item: PersistableEvidence) -> bool:
    return (item.source_type in _FINANCIAL_FACT_TYPES) or bool(item.primary_fact)


def _bounded_council_quote(item: PersistableEvidence) -> str | None:
    """A bounded source_quote for a council citation.

    Metadata-only references assert NO fact — never invent a fact-like quote for
    them (they get ``None``). Otherwise return the bounded excerpt (if any).
    """
    if _is_metadata_only(item):
        return None
    excerpt = item.excerpt
    if not excerpt:
        return None
    return excerpt[:_COUNCIL_QUOTE_MAX]


def _council_evidence_links(
    council_result: Any,
) -> list[tuple[str, str, PersistableEvidence]]:
    """Resolve each COMPLETED-agent claim→E# link to its evidence item.

    Returns ``(agent_name, claim_text, evidence_item)`` for every key_point and
    risk/gap that carries a citation_id resolvable to a retained pack item. Failed
    / skipped agents (empty key_points) contribute nothing. An ``E#`` that does not
    resolve is skipped (never fabricated). Deterministic order = agent order then
    claim order then citation order, so the projected appendix count matches the
    rows actually persisted.
    """
    by_alias: dict[str, PersistableEvidence] = {
        it.alias: it
        for it in (getattr(council_result, "persistable_evidence", None) or [])
    }
    links: list[tuple[str, str, PersistableEvidence]] = []
    if not by_alias:
        return links
    # Dedup identical (agent, claim, alias) triples so a claim that repeats the
    # same citation_id (e.g. ["E1", "E1"]) yields ONE citation, not two — the
    # same claim cannot cite the same evidence item twice. Distinct claims that
    # cite the same alias still each produce a link (one citation per claim).
    seen: set[tuple[str, str, str]] = set()

    def _emit(agent_name: str, claim: str, cid: str) -> None:
        item = by_alias.get(cid)
        if item is None:
            return
        key = (agent_name, claim, item.alias)
        if key in seen:
            return
        seen.add(key)
        links.append((agent_name, claim, item))

    for agent in getattr(council_result, "agents", None) or []:
        if getattr(agent, "status", None) != STATUS_COMPLETED:
            continue
        for kp in getattr(agent, "key_points", None) or []:
            for cid in getattr(kp, "citation_ids", None) or []:
                _emit(agent.agent_name, kp.claim, cid)
        for rg in getattr(agent, "risks_or_gaps", None) or []:
            for cid in getattr(rg, "citation_ids", None) or []:
                _emit(agent.agent_name, rg.item, cid)
    return links


async def _get_or_create_evidence_source_id(
    db: AsyncSession,
    item: PersistableEvidence,
    canonical_url: str | None,
    seen: dict[str, uuid.UUID],
) -> uuid.UUID:
    """Flush-only ``get_or_create`` for one evidence item's canonical Source.

    Deduped by ``content_hash`` (so url-less SEC facts dedup and re-runs never
    accumulate duplicate sources): first the in-run cache, then an existing DB row,
    else a new ``Source``. A DEEP primary-document item uses its RAW-bytes document
    hash (one Source per distinct document — Slice 5 C4); every other item keeps
    the synthesized url+tier+excerpt hash. ``db.add`` + ``db.flush`` ONLY — no
    commit — so the whole final-report persistence stays in one transaction (the
    service ``create_source`` commits internally and must NOT be reused here).
    """
    content_hash = _source_content_hash(item, canonical_url)
    cached = seen.get(content_hash)
    if cached is not None:
        return cached
    existing = await db.execute(
        select(Source).where(Source.content_hash == content_hash).limit(1)
    )
    row = existing.scalar_one_or_none()
    if row is not None:
        seen[content_hash] = row.id
        return row.id
    source = Source(
        id=uuid.uuid4(),
        source_type=item.source_type or "source",
        title=(item.title or "Council evidence source")[:_SOURCE_TITLE_MAX],
        url=canonical_url,
        publisher=item.provider_transport,
        retrieved_at=_utcnow(),
        content_hash=content_hash,
    )
    db.add(source)
    await db.flush()
    seen[content_hash] = source.id
    return source.id


async def _persist_council_evidence_citations(
    db: AsyncSession,
    report_id: uuid.UUID,
    agent_run_id: uuid.UUID | None,
    council_result: Any,
) -> tuple[int, int]:
    """Persist COMPLETED-agent claim→evidence links as Source + Citation rows.

    Idempotent within a report: any prior ``council:%`` citations for this report
    are deleted first (the report is new, so normally none). Sources are deduped
    by content_hash; a metadata-only reference is persisted as a REFERENCE (no
    fact-like source_quote, ``data_quality`` keeps the metadata-only sentinel) so
    it can never be classified/counted as a financial fact. Flush-only — the
    caller owns the single commit. Returns ``(sources_added_or_reused,
    citations_added)`` for count logging.
    """
    await db.execute(
        delete(Citation).where(
            Citation.report_id == report_id,
            Citation.field_path.like(f"{_COUNCIL_FIELD_PATH_PREFIX}%"),
        )
    )
    links = _council_evidence_links(council_result)
    if not links:
        return (0, 0)
    seen_sources: dict[str, uuid.UUID] = {}
    citations_added = 0
    now = _utcnow()
    for agent_name, claim_text, item in links:
        canonical_url = canonicalize_source_url(item.url)
        source_id = await _get_or_create_evidence_source_id(
            db, item, canonical_url, seen_sources
        )
        db.add(
            Citation(
                id=uuid.uuid4(),
                source_id=source_id,
                report_id=report_id,
                agent_run_id=agent_run_id,
                claim_text=claim_text,
                source_quote=_bounded_council_quote(item),
                url=canonical_url,
                retrieved_at=now,
                field_path=f"{_COUNCIL_FIELD_PATH_PREFIX}{agent_name}",
                source_tier=item.source_tier,
                data_quality=item.data_quality,
            )
        )
        citations_added += 1
    await db.flush()
    return (len(seen_sources), citations_added)


def _evidence_reconciliation_counts(
    council_result: Any,
    deterministic_citations: list[Citation],
    references: list[dict[str, Any]],
    source_reference_counts: dict[str, int],
) -> dict[str, int]:
    """The SIX honest, side-by-side appendix counts (NEVER summed).

    Projects the DB-persisted counts from the same deterministic inputs the
    persistence layer uses, so the appendix agrees with the rows that will exist:
    deterministic draft citations (surfaced via the fallback loader) + the council
    claim→evidence links. Distinct sources are counted by identity (deterministic
    source_id ∪ synthesized council content_hash) so a source cited by N claims is
    one source / N citations, and references/facts are never conflated with rows.
    """
    persistable = list(getattr(council_result, "persistable_evidence", None) or [])
    extracted = 0
    financial = 0
    for it in persistable:
        if _is_financial_fact(it):
            financial += 1
            continue
        if _is_metadata_only(it):
            continue  # a located reference is neither extracted nor a fact
        if (it.excerpt or "").strip():
            extracted += 1

    links = _council_evidence_links(council_result)
    council_link_count = len(links)
    # Use the SAME per-item Source key the persistence layer uses (raw-bytes hash
    # for deep primary documents, synthesized hash otherwise) so this projected
    # ``db_persisted_source_count`` equals the rows actually written — deep excerpts
    # + facts from one document collapse to one Source, never inflated.
    council_source_hashes = {
        _source_content_hash(it, canonicalize_source_url(it.url))
        for _, _, it in links
    }
    # Count ONLY genuinely-deterministic (non-council) lineage citations here.
    # ``council:%`` rows are this report's own council links and are already
    # counted via ``council_link_count`` / ``council_source_hashes``; counting
    # them again as "deterministic" would double-count. This also fails safe if a
    # source report ever carries council citations (defense-in-depth beyond the
    # ``generate_from_company`` draft-only selection). Keeps the STORED appendix
    # count equal to a fresh ``_load_citations_for_report(final.id, lineage)``.
    det_rows = [
        c
        for c in deterministic_citations
        if not (c.field_path or "").startswith(_COUNCIL_FIELD_PATH_PREFIX)
    ]
    det_source_ids = {c.source_id for c in det_rows}
    ref_count = (source_reference_counts or {}).get(
        "primary_source_reference_count", len(references)
    )
    return {
        "primary_source_reference_count": int(ref_count),
        "extracted_evidence_count": extracted,
        "structured_financial_fact_count": financial,
        "db_persisted_source_count": len(det_source_ids) + len(council_source_hashes),
        "db_persisted_citation_count": len(det_rows) + council_link_count,
        "council_claim_citation_count": council_link_count,
    }


# Deep primary-document extraction statuses (mirror ``primary_document_extractor``
# — kept local to avoid importing the connector layer into the report generator).
_DEEP_STATUS_EXTRACTED = "extracted"
_DEEP_STATUS_METADATA_ONLY = "metadata_only"
_DEEP_STATUS_EXTRACTION_FAILED = "extraction_failed"


def _primary_document_citation_rows(council_result: Any) -> list[dict[str, Any]]:
    """Citation representation for DEEP primary-document claim→evidence links.

    Phase 32A Slice 5 (C3): each row surfaces the page / section / table location /
    extraction method / confidence for a council claim backed by extracted
    primary-document evidence — the page/section carried through the
    ``PersistableEvidence`` carrier (there is no citations JSON column, so this
    lives in the report's citation representation, not a new DB column). Only DEEP
    items appear (``document_content_hash`` present); a metadata-only reference is
    NEVER included (it verifies no claim). OCR-derived evidence discloses its OCR
    provenance. Carries no raw document text — bounded provenance + claim only.
    """
    rows: list[dict[str, Any]] = []
    for agent_name, claim_text, item in _council_evidence_links(council_result):
        prov = _primary_document_provenance(item)
        if prov is None:
            continue
        row: dict[str, Any] = {
            "agent": agent_name,
            "claim_text": claim_text,
            "source_type": item.source_type,
            "source_tier": item.source_tier,
            "page_number": prov["page_number"],
            "section": prov["section"],
            "table_location": prov["table_location"],
            "extraction_method": prov["extraction_method"],
            "confidence": prov["confidence"],
            "document_content_hash": prov["document_content_hash"],
        }
        if "ocr_disclosure" in prov:
            row["ocr_disclosure"] = prov["ocr_disclosure"]
        rows.append(row)
    return rows


def _primary_document_state_counts(council_result: Any) -> dict[str, int]:
    """Distinct, honest per-document ingestion-state counts (NEVER summed).

    Phase 32A Slice 5 (C4): extracted vs metadata-only vs extraction-failed are
    three separate states of the deep artifacts handed off for this run. Reported
    side-by-side so the appendix is honest about which documents yielded text,
    which located only metadata, and which failed (surfaced as gaps elsewhere).
    """
    extracted = 0
    metadata_only = 0
    failed = 0
    for art in getattr(council_result, "primary_document_artifacts", None) or []:
        status = getattr(art, "status", None)
        if status == _DEEP_STATUS_EXTRACTED:
            extracted += 1
        elif status == _DEEP_STATUS_METADATA_ONLY:
            metadata_only += 1
        elif status == _DEEP_STATUS_EXTRACTION_FAILED:
            failed += 1
    return {
        "primary_document_extracted_count": extracted,
        "primary_document_metadata_only_count": metadata_only,
        "primary_document_extraction_failed_count": failed,
    }


