def run_safety_gate(report_content: dict[str, Any]) -> SafetyValidationResult:
    """
    Scan all text in the report for forbidden output terms.

    Delegates to the shared three-tier scanner in ``app.services.safety_terms``:
    ALL-CAPS rating labels (BUY/SELL/HOLD/...), rating-context phrasing
    ("Rating: Buy"), and multi-word phrases (price target, fair value, ...).

    Returns a SafetyValidationResult. If any forbidden term is found:
      - passed=False
      - blocks_approval=True
      - report must be saved as draft only
      - human revision is required before approval

    Note: certain field names are exempt from scanning because they exist to
    explicitly enumerate what is NOT produced (e.g. disallowed_outputs from the
    valuation guard agent). Scanning these would generate false positives.
    """
    found_terms: list[str] = []
    scanned_sections: list[str] = []
    warnings: list[str] = []

    for section_name, section_content in report_content.items():
        scanned_sections.append(section_name)
        found_terms.extend(
            safety_terms.hits_to_strings(
                safety_terms.scan_value(
                    section_content,
                    path=section_name,
                    exempt_keys=_EXEMPT_FIELD_NAMES,
                )
            )
        )

    passed = len(found_terms) == 0
    if not passed:
        warnings.append(
            "SAFETY GATE FAILURE: Forbidden output terms detected. "
            "Report saved as draft only. Human revision required before approval."
        )

    return SafetyValidationResult(
        passed=passed,
        forbidden_terms_found=found_terms,
        scanned_sections=scanned_sections,
        warnings=warnings,
        blocks_approval=not passed,
    )


