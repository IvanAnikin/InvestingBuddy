def _primary_fact_dp(fact: dict[str, Any]) -> dict[str, Any]:
    """Datapoint for a parsed T1 primary-filing fact — Phase 29B.3.

    Unlike ``_fund_dp`` (which stamps an EODHD / T5 aggregator value), this stamps
    the fact's OWN token-stripped source URL, ``source_tier="T1_primary_filing"``,
    a short provenance (page / excerpt id / confidence), and is always
    ``human_review_required``. ``provenance="sourced_fact"`` is only emitted when
    the fact actually carries its source URL — never a bare "sourced_fact".
    """
    source_url = fact.get("source_url")
    prov_bits: list[str] = []
    page = fact.get("page_number")
    if page is not None:
        prov_bits.append(f"page={page}")
    if fact.get("excerpt_id"):
        prov_bits.append(f"excerpt={fact['excerpt_id']}")
    if fact.get("confidence"):
        prov_bits.append(f"confidence={fact['confidence']}")
    return {
        "value": fact.get("value"),
        "numeric_value": fact.get("numeric_value"),
        "unit": fact.get("unit"),
        "currency": fact.get("currency"),
        "scale": fact.get("scale"),
        "period": fact.get("period"),
        "provenance": "sourced_fact" if source_url else "missing_data",
        "source_tier": "T1_primary_filing",
        "source": "company_ir_primary_document",
        "source_url": source_url,
        "fact_provenance": prov_bits,
        "confidence": fact.get("confidence"),
        "needs_human_review": True,
        "human_review_required": True,
    }


def _high_confidence_facts_for(
    primary_facts: list[dict[str, Any]] | None,
    fields: frozenset[str],
) -> list[tuple[str, dict[str, Any]]]:
    """(field, fact) pairs for high-confidence facts whose field is in ``fields``.

    De-duplicates on field (first high-confidence fact wins) so a section never
    grows two datapoints for the same field.
    """
    out: list[tuple[str, dict[str, Any]]] = []
    seen: set[str] = set()
    for fact in primary_facts or []:
        field = fact.get("field")
        if field not in fields or field in seen:
            continue
        if fact.get("confidence") != "high":
            continue
        seen.add(field)  # type: ignore[arg-type]
        out.append((field, fact))  # type: ignore[arg-type]
    return out


def _build_company_identity(
    company_snapshot: dict[str, Any] | None,
    company_record: dict[str, Any] | None,
    primary_facts: list[dict[str, Any]] | None = None,
) -> dict[str, Any]:
    identity: dict[str, Any] = {"type": "company_identity"}

    def _dp(value: Any, source: str, provenance: str = "sourced_fact") -> dict:
        return {
            "value": value,
            "source": source,
            "provenance": provenance,
            "human_review_required": value is None,
        }

    if company_snapshot:
        ci = company_snapshot.get("company_identity", {})
        profile = company_snapshot.get("profile", {})
        identity["legal_name"] = _dp(ci.get("legal_name"), "company_snapshot")
        identity["ticker"] = _dp(ci.get("ticker"), "company_snapshot")
        identity["exchange"] = _dp(ci.get("exchange"), "company_snapshot")
        identity["country_domicile"] = _dp(
            ci.get("country_domicile"), "company_snapshot"
        )
        identity["isin"] = _dp(
            ci.get("isin"),
            "company_snapshot",
            "missing_data" if not ci.get("isin") else "sourced_fact",
        )
        identity["lei"] = _dp(
            ci.get("lei"),
            "company_snapshot",
            "missing_data" if not ci.get("lei") else "sourced_fact",
        )
        identity["sector"] = _dp(
            profile.get("sector"), "company_snapshot.profile"
        )
        identity["reporting_currency"] = _dp(
            profile.get("reporting_currency"), "company_snapshot.profile"
        )
        identity["source_tier"] = company_snapshot.get(
            "source_tier", "T6_model_estimate"
        )
        # Phase 32A AD-2 — tri-state provenance from the EXPLICIT snapshot signal.
        _prov = derive_data_provenance(company_snapshot.get("is_mock"))
        identity["data_provenance"] = _prov
        identity["is_mock"] = provenance_to_is_mock(_prov)
    elif company_record:
        identity["legal_name"] = _dp(company_record.get("name"), "company_db_record")
        identity["ticker"] = _dp(company_record.get("ticker"), "company_db_record")
        identity["exchange"] = _dp(company_record.get("exchange"), "company_db_record")
        identity["country_domicile"] = _dp(
            company_record.get("country"), "company_db_record"
        )
        identity["sector"] = _dp(
            company_record.get("sector"), "company_db_record"
        )
        identity["source_tier"] = "T6_model_estimate"
        # Phase 32A RC-2/RC-5 — a real, known parent recovered from the DB is
        # REAL identity, never mock. A missing financial snapshot does NOT make a
        # known company "mock" (the number-suppression provenance is separate).
        identity["data_provenance"] = "real"
        identity["is_mock"] = False
    else:
        identity["legal_name"] = _dp(None, "unavailable", "missing_data")
        identity["source_tier"] = "T6_model_estimate"
        # Phase 32A AD-2 — no snapshot and no DB parent: provenance is genuinely
        # UNKNOWN (is_mock None, honoured), never coerced to mock. Identity stays
        # honestly unresolved + human-review flagged (set below), never fabricated.
        identity["data_provenance"] = "unknown"
        identity["is_mock"] = None

    # Phase 29B.3 — add/override identity datapoints from real high-confidence
    # primary facts (reporting_currency, fiscal_year, employees, …). Each carries
    # the fact's OWN source_url + T1 tier + needs_human_review. With no such fact
    # this loop is a no-op and the section is byte-for-byte unchanged.
    for field, fact in _high_confidence_facts_for(
        primary_facts, _PRIMARY_IDENTITY_FACT_FIELDS
    ):
        identity[field] = _primary_fact_dp(fact)

    identity["human_review_required"] = True
    return identity


