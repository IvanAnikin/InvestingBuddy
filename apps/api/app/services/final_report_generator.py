async def _save_final_report_draft(
    db: AsyncSession,
    report_content: dict[str, Any],
    safety_result: SafetyValidationResult,
    schema_validation: dict[str, Any],
    source_summary: dict[str, Any],
    scorecard_id: uuid.UUID | None,
    company_name: str | None,
    ticker: str | None,
    source_report_id: uuid.UUID | None,
    llm_used: bool = False,
    company_id: uuid.UUID | None = None,
    created_by_agent_run_id: uuid.UUID | None = None,
    council_result: Any = None,
) -> Report:
    """
    Save the assembled final report as a new draft report record.

    Phase 28A.1 — the title honestly reflects whether the LLM analysis council
    ran ("LLM Council Analysis Draft" vs "Internal Analysis Draft"). It NEVER
    says "Phase 9" — this is the final-report-generator path, not the legacy
    deterministic Analysis Council draft. Legacy reports are identified by a
    NULL ``final_report_version``; every report saved here carries a version.
    """
    import json

    # Phase 28A.1 — honest, non-"Phase 9" title. The council-ran variant makes
    # the LLM involvement obvious in report lists without opening the report.
    kind_label = "LLM Council Analysis Draft" if llm_used else "Internal Analysis Draft"
    who = company_name or "Unknown"
    title_prefix = f"{kind_label} — {who}"
    if ticker:
        title_prefix = f"{kind_label} — {ticker} — {who}"

    slug = (
        f"final-report-{ticker or 'unknown'}-{uuid.uuid4().hex[:8]}"
        .lower()
        .replace(" ", "-")
    )

    # Build markdown summary for content_markdown
    content_lines = [
        "# INTERNAL ADMIN DRAFT — FINAL REPORT",
        "",
        "NOT INVESTMENT ADVICE. NOT A PUBLIC TRADING RECOMMENDATION. Human review required.",
        "",
        "---",
        "",
        "## Report Sections (Structured JSON — see safety_validation_json"
        " and schema_validation_json for validation status)",
        "",
        "```json",
        json.dumps(report_content, indent=2, default=str),
        "```",
    ]
    content_markdown = "\n".join(content_lines)

    schema_valid = schema_validation.get("is_valid", False)

    report = Report(
        id=uuid.uuid4(),
        title=title_prefix,
        slug=slug,
        report_type="company_deep_dive",
        status="draft",
        summary=(
            f"{kind_label} for {company_name or 'Unknown'}. "
            f"LLM council: {'used' if llm_used else 'not used'}. "
            f"Safety: {'PASSED' if safety_result.passed else 'FAILED'}. "
            f"Schema: {'valid' if schema_valid else 'invalid'}. "
            f"Human review required."
        ),
        content_markdown=content_markdown,
        review_status="draft",
        human_review_required=True,
        final_report_version=FINAL_REPORT_VERSION,
        safety_validation_json=safety_result.model_dump(),
        schema_validation_json=schema_validation,
        source_summary_json=source_summary,
        scorecard_id=scorecard_id,
    )

    # Phase 32A Slice 3 — carry the resolved lineage onto the final report so it
    # is a first-class member of the public research entity (not an orphan). The
    # source_report_id param is no longer discarded: the caller resolved
    # ``company_id`` + ``created_by_agent_run_id`` off the SOURCE report (from
    # report / from company) or the workflow state (from workflow state), or left
    # them None when genuinely unknown (never fabricated). OFF ⇒ both stay NULL, so
    # a regenerated report is byte-identical to today.
    if settings.report_citation_persistence_enabled:
        report.company_id = company_id
        report.created_by_agent_run_id = created_by_agent_run_id

    db.add(report)
    await db.flush()

    # Phase 32A Slice 3 — persist the council's claim→evidence citations for this
    # NEW report BEFORE the single commit, so a cited E# alias becomes a durable
    # Source + Citation row. Flush-only (no inner commit) ⇒ the whole final-report
    # write stays atomic. Never crosses a company (keyed by report_id + the
    # company-pinned lineage agent_run). OFF / no council ⇒ no-op.
    if settings.report_citation_persistence_enabled and council_result is not None:
        sources_touched, citations_added = await _persist_council_evidence_citations(
            db, report.id, created_by_agent_run_id, council_result
        )
        log_event(
            logger,
            "council_citations_persisted",
            report_id=str(report.id),
            council_sources=sources_touched,
            council_citations=citations_added,
        )

    # Phase 32A Slice 5 (3c-i) — persist the council's DEEP primary-document
    # artifacts (ExtractedDocument / ExtractedFact) for this run's lineage. Gated
    # behind BOTH the ingestion + citation-persistence flags (either off ⇒ no
    # query, no row). Lineage is attached via company_id / agent_run_id only — it
    # never touches the from-company selection (Slice-3 "B1" invariant). Best
    # effort: wrapped in a SAVEPOINT so a persistence error rolls back ONLY the
    # ingestion rows (never the report / citations) and never breaks report
    # generation; the failure is logged by exception TYPE NAME only (no secrets).
    if (
        settings.primary_document_ingestion_enabled
        and settings.report_citation_persistence_enabled
        and council_result is not None
    ):
        try:
            async with db.begin_nested():
                persist_result = await persist_primary_document_artifacts(
                    db,
                    artifacts=getattr(
                        council_result, "primary_document_artifacts", None
                    ),
                    company_id=company_id,
                    agent_run_id=created_by_agent_run_id,
                    cfg=settings,
                )
            log_event(
                logger,
                "primary_documents_persisted",
                report_id=str(report.id),
                documents_created=persist_result.documents_created,
                documents_reused=persist_result.documents_reused,
                facts_created=persist_result.facts_created,
                facts_deduped=persist_result.facts_deduped,
                skipped=persist_result.skipped,
            )
        except Exception as exc:  # noqa: BLE001 - ingestion never breaks a report
            log_event(
                logger,
                "primary_documents_persist_failed",
                level=logging.WARNING,
                report_id=str(report.id),
                exception_type=type(exc).__name__,
            )

    # Persist the draft. get_db() does not commit for us (it yields the session
    # and closes it, which rolls back an uncommitted transaction), so every
    # write service commits its own work — this one must too, or the generated
    # final-report draft (and its final_report_version / validation JSON) is
    # silently discarded when the request ends.
    await db.commit()
    await db.refresh(report)
    return report


