    async def validate_final_report(
        self, db: AsyncSession, report_id: uuid.UUID
    ) -> FinalReportValidateResponse:
        """Re-validate an existing final report (safety + schema)."""
        report = await _load_report_by_id(db, report_id)
        if report is None:
            raise ValueError(f"Report {report_id} not found.")

        import json

        # Parse the content for safety + schema validation
        report_content: dict[str, Any] = {}
        if report.content_markdown:
            import re

            pattern = re.compile(r"```json\s*(.*?)\s*```", re.DOTALL)
            for match in pattern.finditer(report.content_markdown):
                try:
                    block = json.loads(match.group(1))
                    if isinstance(block, dict):
                        report_content = block
                        break
                except (json.JSONDecodeError, ValueError):
                    pass

        # Phase 26: safety-scan the admin draft AND validate a schema-completed
        # version so a research-incomplete draft can still reach schema_valid=True
        # via honest not_sourced stand-ins (never fabricated data).
        validation = run_final_report_validation(
            report_content,
            report_id=str(report.id),
            generated_at=report.created_at,
        )

        sections_present = [k for k in report_content if k in _REQUIRED_SECTIONS]
        missing_sections = [s for s in _REQUIRED_SECTIONS if s not in report_content]

        # ── Telemetry (Phase 27.1D) — booleans + counts only, never content ──
        # Emits validation outcomes so a staging operator can confirm the safety
        # posture (human_review_required stays True, publication_ready stays
        # False) without opening the report. The report body is never logged.
        log_event(
            logger,
            "report_validation",
            report_id=report.id,
            schema_valid=validation.schema_valid,
            safety_valid=validation.safety_valid,
            research_complete=validation.research_complete,
            publication_ready=validation.publication_ready,
            human_review_required=True,
            forbidden_terms_count=len(validation.safety_result.forbidden_terms_found),
            missing_required_sections_count=len(missing_sections),
        )

        # Update the report's validation fields
        report.safety_validation_json = validation.safety_result.model_dump()
        report.schema_validation_json = validation.persisted_schema_json
        await db.flush()
        # Commit so the safety/schema validation JSON actually persists on the
        # report row. Without this, get_db() rolls back on session close and the
        # report-detail page keeps showing "Safety/Schema Validation: n/a".
        await db.commit()

        return FinalReportValidateResponse(
            report_id=report.id,
            schema_valid=validation.schema_valid,
            safety_valid=validation.safety_valid,
            human_review_required=True,
            research_complete=validation.research_complete,
            publication_ready=validation.publication_ready,
            safety_validation=validation.safety_result,
            schema_validation_errors=validation.schema_errors,
            schema_validation_warnings=validation.schema_warnings,
            validation_warnings=validation.validation_warnings,
            sections_present=sections_present,
            missing_sections=missing_sections,
        )

    async def regenerate_report_section(
        self, db: AsyncSession, report_id: uuid.UUID, section_name: str
    ) -> RegenerateSectionResponse:
        """Regenerate a single section of an existing final report."""
        if section_name not in _REQUIRED_SECTIONS:
            raise ValueError(
                f"Unknown section '{section_name}'. "
                f"Valid sections: {sorted(_REQUIRED_SECTIONS)}"
            )

        report = await _load_report_by_id(db, report_id)
        if report is None:
            raise ValueError(f"Report {report_id} not found.")

        # For deterministic regeneration, rebuild the section from workflow state
        state = _extract_workflow_state_from_report(report)
        scorecard: Scorecard | None = None
        if report.scorecard_id:
            scorecard = await _load_scorecard_by_id(db, report.scorecard_id)

        # Build only the requested section
        section_content: dict[str, Any] = {}
        match section_name:
            case "admin_disclaimer":
                section_content = _build_admin_disclaimer()
            case "executive_summary":
                section_content = _build_executive_summary(
                    None, None, scorecard,
                    state.get("committee_chair_summary"),
                    state.get("committee_chair_summary", {}).get(
                        "provisional_internal_status"
                    ) if state.get("committee_chair_summary") else None,
                )
            case "internal_scorecard":
                section_content = _build_internal_scorecard(scorecard)
            case "valuation_readiness":
                section_content = _build_valuation_readiness(
                    state.get("valuation_guard_summary"), scorecard
                )
            case "bull_case":
                section_content = _build_bull_case(state.get("bull_case_summary"))
            case "bear_case":
                section_content = _build_bear_case(state.get("bear_case_summary"))
            case "risk_analysis":
                section_content = _build_risk_analysis(state.get("risk_summary"))
            case "committee_chair_summary":
                section_content = _build_committee_chair_summary(
                    state.get("committee_chair_summary")
                )
            case "research_completeness_review":
                section_content = _build_research_completeness_review(
                    state.get("research_completeness_summary")
                )
            case _:
                section_content = {
                    "note": f"Section '{section_name}' requires full report regeneration.",
                    "provenance": "missing_data",
                }

        safety_result = run_safety_gate({section_name: section_content})

        warnings: list[str] = list(safety_result.warnings)
        if not safety_result.passed:
            warnings.append(
                f"Section '{section_name}' contains forbidden terms. "
                "Cannot update report section."
            )

        return RegenerateSectionResponse(
            report_id=report.id,
            section_name=section_name,
            regenerated=safety_result.passed,
            safety_valid=safety_result.passed,
            warnings=warnings,
        )

    # ── Core private assembly ─────────────────────────────────────────────────

    async def _generate_and_save(
        self,
        db: AsyncSession,
        scorecard: Scorecard | None,
        candidate: ScreeningCandidate | None,
        source_report: Report | None,
        company_record: dict[str, Any] | None,
        citations: list[Citation],
        sources: list[Source],
        state: dict[str, Any],
    ) -> FinalReportResponse:
        company_snapshot = state.get("company_snapshot")
        financial_data_summary = state.get("financial_data_summary")
        source_quality_summary = state.get("source_quality_summary")
        research_completeness_summary = state.get("research_completeness_summary")
        upgraded_citation_validation = state.get("upgraded_citation_validation")
        bull_case_summary = state.get("bull_case_summary")
        bear_case_summary = state.get("bear_case_summary")
        risk_summary = state.get("risk_summary")
        valuation_guard_summary = state.get("valuation_guard_summary")
        committee_chair_summary = state.get("committee_chair_summary")
        fundamentals_data = state.get("fundamentals_data")
        fundamentals_available = state.get("fundamentals_available")
        schema_validation_result = state.get("schema_validation_result")
        catalyst_discovery = state.get("catalyst_discovery")
        source_tier = state.get("source_tier") or (
            company_snapshot.get("source_tier") if company_snapshot else None
        )

        schema_valid = (
            schema_validation_result.get("is_valid", False)
            if schema_validation_result
            else False
        )
        human_review_required = True

        # Phase 32A AD-2 — one report-level provenance from explicit signals only
        # (snapshot ⇒ scorecard ⇒ unknown). Reused for the checklist mock flag and
        # the auditable source-summary metadata; never coerced to mock on absence.
        report_provenance = _derive_report_provenance(company_snapshot, scorecard)

        report_content = _assemble_final_report_content(
            company_snapshot=company_snapshot,
            company_record=company_record,
            candidate=candidate,
            scorecard=scorecard,
            financial_data_summary=financial_data_summary,
            source_quality_summary=source_quality_summary,
            research_completeness_summary=research_completeness_summary,
            upgraded_citation_validation=upgraded_citation_validation,
            bull_case_summary=bull_case_summary,
            bear_case_summary=bear_case_summary,
            risk_summary=risk_summary,
            valuation_guard_summary=valuation_guard_summary,
            committee_chair_summary=committee_chair_summary,
            fundamentals_data=fundamentals_data,
            fundamentals_available=fundamentals_available,
            source_tier=source_tier,
            sources=sources,
            citations=citations,
            report=source_report,
            agent_run_id=str(source_report.created_by_agent_run_id)
            if source_report and source_report.created_by_agent_run_id
            else None,
            schema_valid=schema_valid,
            human_review_required=human_review_required,
            catalyst_discovery=catalyst_discovery,
        )

        # Derive identity early — needed for both the council and the title.
        company_name: str | None = None
        ticker: str | None = None
        exchange: str | None = None
        if company_snapshot:
            ci = company_snapshot.get("company_identity", {})
            company_name = ci.get("legal_name")
            ticker = ci.get("ticker")
            exchange = ci.get("exchange")
        elif company_record:
            company_name = company_record.get("name")
            ticker = company_record.get("ticker")
            exchange = company_record.get("exchange")
        elif candidate:
            company_name = candidate.name
            ticker = candidate.ticker
            exchange = candidate.exchange

        # Phase 28A: optional single-company LLM analysis council. Runs ONLY when
        # LLM_COUNCIL_ENABLED and a provider resolves; otherwise returns a
        # disabled result and the deterministic path below is unchanged. Council
        # output is added to report_content BEFORE validation so the existing
        # safety gate scans it (backstop on top of the council's own quarantine).
        appendix = report_content.get("source_citation_appendix", {}) or {}
        source_rows = (appendix.get("sources") or {}).get("value") or []
        council_result: CouncilResult = await maybe_run_council(
            report_content=report_content,
            company_snapshot=company_snapshot,
            catalyst_discovery=catalyst_discovery,
            source_rows=source_rows,
            report_id=None,
            ticker=ticker,
            exchange=exchange,
        )
        if council_result.llm_used:
            report_content["llm_council_analysis"] = council_result.to_report_dict()

        # Phase 29B.3: when the council surfaced real high-confidence primary facts
        # (annual-report revenue / reporting currency / fiscal year / …), re-render
        # the financial-snapshot + company-identity sections so each fact appears
        # as a T1 datapoint carrying its OWN source_url + tier + provenance +
        # needs_human_review. The existing T5 eodhd datapoints are preserved. With
        # zero facts (the scanned-PDF reality) both sections stay byte-for-byte
        # identical. This runs BEFORE validation so the safety gate scans it.
        primary_facts = council_result.primary_facts
        if primary_facts:
            report_content["financial_snapshot"] = _build_financial_snapshot(
                company_snapshot, fundamentals_data, primary_facts=primary_facts
            )
            report_content["company_identity"] = _build_company_identity(
                company_snapshot, company_record, primary_facts=primary_facts
            )
            # Phase 29B.3: the quality gates were assembled before the council ran,
            # so re-derive the ones that recognise real T1 primary facts. The
            # source-quality review now flags EXTRACTED primary facts (distinct
            # from metadata-only IR links), and the T1/T2 data-quality checklist
            # item is recomputed (still gated on not-mock). With zero facts none
            # of this runs and the report is byte-for-byte unchanged.
            report_content["source_quality_review"] = _build_source_quality_review(
                source_quality_summary, sources, primary_facts=primary_facts
            )
            # Phase 32A RC-2 — mock ONLY on explicit provenance; unknown ≠ mock.
            _patch_t1_t2_checklist_item(
                report_content.get("human_review_checklist", []),
                is_mock=(report_provenance == "mock"),
                has_t1_t2=_has_t1_t2_evidence(source_tier, citations, primary_facts),
            )

        # Phase 31 hotfix: when the connector layer located verified PRIMARY-SOURCE
        # REFERENCES (metadata-only issuer IR / filing-index / regulator venues) but
        # no DB citation was persisted, record the reference COUNT on the source
        # citation appendix so the report does not imply there are zero source
        # references. This never fabricates a Source/Citation row — it is an honest
        # count + note pointing at the research memo's Primary Evidence. Dark by
        # default: with the connector layer off there are no references and the
        # appendix is byte-for-byte unchanged.
        _refs = getattr(council_result, "primary_source_references", None) or []
        _appendix = report_content.get("source_citation_appendix")
        if _refs and isinstance(_appendix, dict):
            _ref_count = (
                getattr(council_result, "source_reference_counts", {}) or {}
            ).get("primary_source_reference_count", len(_refs))
            _appendix["primary_source_reference_count"] = _ref_count
            # Only point at the research memo when it is actually rendered; with the
            # memo flag off the references are surfaced by the count alone.
            _memo_pointer = (
                " and are listed in the Internal Research Memo (Primary Evidence)"
                if settings.source_research_memo_enabled
                else ""
            )
            _appendix["note"] = (
                f"{_ref_count} verified primary-source reference(s) (issuer investor "
                "relations / annual-report index / regulator venue) were located by "
                f"the source-connector layer{_memo_pointer}. DB-persisted workflow "
                "citations remain as counted above; a metadata-only reference is not "
                "yet a persisted citation and requires human review."
            )

        # Phase 32A Slice 3 — honest source/citation reconciliation. Extend the
        # appendix with SIX independent, side-by-side counts (NEVER summed into one
        # total — that would double/triple-count the same underlying source, per the
        # agent-D warning). The existing ``sources``/``citations`` {value,total}
        # envelopes are now non-zero via the fallback loader; these counts add the
        # evidence-pack + persistence view and a reconciling ``note`` that never
        # implies "no sources" while council claim citations exist. Dark by default:
        # with the flag off this block does not run and the appendix wording is
        # byte-for-byte unchanged.
        if settings.report_citation_persistence_enabled and isinstance(
            _appendix, dict
        ):
            _counts = _evidence_reconciliation_counts(
                council_result,
                citations,
                _refs,
                getattr(council_result, "source_reference_counts", {}) or {},
            )
            _appendix.update(_counts)
            _appendix["note"] = _APPENDIX_RECONCILE_NOTE

        # Phase 32A Slice 5 (C3 + C4) — honest DEEP primary-document surfacing.
        # When the master ingestion flag is on, extend the appendix with (a) the
        # per-document ingestion-state counts (extracted / metadata-only / failed —
        # distinct honest states, never summed) and (b) the primary-document
        # citation representation carrying page / section / table location +
        # extraction method + confidence (+ OCR disclosure) for each council claim
        # backed by extracted primary-document evidence. Both are additive and only
        # appear when non-empty. Dark by default: with the master flag off (or no
        # deep documents) nothing is added and the appendix is byte-for-byte
        # unchanged. A metadata-only reference never appears here as verification.
        if settings.primary_document_ingestion_enabled and isinstance(
            _appendix, dict
        ):
            _state_counts = _primary_document_state_counts(council_result)
            _pd_citations = _primary_document_citation_rows(council_result)
            if any(_state_counts.values()) or _pd_citations:
                _appendix.update(_state_counts)
                _appendix["primary_document_citations"] = {
                    "value": _pd_citations,
                    "total": len(_pd_citations),
                    "provenance": "sourced_fact",
                }
                _appendix["primary_document_note"] = _APPENDIX_PRIMARY_DOC_NOTE

        # Phase 29C.1: optional MACRO CONTEXT block. When ``source_macro_enabled``
        # is on and the council surfaced reference-only macro sources for this
        # company's broad theme, render them as an OPTIONAL industry_macro_context
        # block (background only — never a company catalyst or recommendation, no
        # figures). Not a required section and not part of the schema-complete
        # shape, so schema_valid is unaffected. Dark by default: with the flag off
        # macro_context is empty and no block is added, so the report is
        # byte-for-byte unchanged. Added BEFORE validation so the safety gate
        # scans it.
        if council_result.macro_context:
            report_content["industry_macro_context"] = _build_industry_macro_context(
                council_result.macro_context
            )

        # Phase 29D.1: optional EVENT CONTEXT block. When ``source_event_enabled``
        # is on and the council surfaced reference-only procurement / tender
        # sources for this company's broad theme, render them as an OPTIONAL
        # industry_event_context block (WEAK research-priority background only —
        # never a company-specific award, catalyst, materiality claim, or trade
        # signal; no figures / dates). Not a required section and not part of the
        # schema-complete shape, so schema_valid is unaffected. Dark by default and
        # independent of the macro flag: with the event flag off event_context is
        # empty and no block is added, so the report is byte-for-byte unchanged.
        # Added BEFORE validation so the safety gate scans it.
        if council_result.event_context:
            report_content["industry_event_context"] = _build_industry_event_context(
                council_result.event_context
            )

        # Phase 30A: optional TRANSLATED EVIDENCE block. When
        # ``source_translation_enabled`` is on and the council produced bounded,
        # machine-assisted English renderings of non-English source excerpts, render
        # them as an OPTIONAL translated_evidence block. Each entry preserves the
        # original excerpt + source URL (the citation of record) and is clearly
        # marked NOT an official translation (human review required) — additive
        # context, never a replacement for the original evidence. Not a required
        # section, so schema_valid is unaffected. Dark by default: with the flag off
        # translated_excerpts is empty and no block is added, so the report is
        # byte-for-byte unchanged. Added BEFORE validation so the safety gate scans
        # it.
        if council_result.translated_excerpts:
            report_content["translated_evidence"] = _build_translated_evidence(
                council_result.translated_excerpts
            )

        # Phase 31: optional INTERNAL RESEARCH MEMO block. When
        # ``source_research_memo_enabled`` is on, synthesise a DETERMINISTIC,
        # citation-bound memo from the already-assembled report_content sections +
        # council_result metadata + known gaps — no ORM query, no LLM call, no
        # external fetch, no recompute. ``what_is_missing`` is prominent and the
        # memo degrades honestly when evidence is thin (no primary facts / no
        # council / blocked extraction). Additive (not a required section) so
        # schema_valid is unaffected; publication stays impossible and human review
        # is always required. Dark by default: with the flag off no block is added
        # and the report is byte-for-byte unchanged. Added BEFORE validation so the
        # safety gate scans it (its forbidden-term notice lives only in the exempt
        # ``disallowed_outputs`` field, so it does not self-trip).
        if settings.source_research_memo_enabled:
            report_content["research_memo"] = _build_research_memo(
                report_content, council_result, source_tier=source_tier
            )

        # Phase 26: safety-scan the admin draft AND validate a schema-completed
        # version (honest not_sourced stand-ins fill genuinely-absent fields, so
        # the draft reaches schema_valid=True while staying research-incomplete).
        validation = run_final_report_validation(
            report_content,
            report_id=str(uuid.uuid4()),
            generated_at=_utcnow(),
        )
        safety_result = validation.safety_result

        # Phase 32A RC-6 — recompute the persisted human-review checklist +
        # workflow status from the FINAL validation flags, BEFORE saving, so the
        # stored report body can never contradict the header. The safety item is
        # sourced from the real gate (validation.safety_valid) — never the
        # assembly-time placeholder at safety_valid=True — and the schema item now
        # reflects the post-completion schema_valid, eliminating the stale
        # "Schema invalid" note. publication_ready (stays False) and
        # human_review_required (stays True) are NOT touched.
        missing_count_val = report_content.get("missing_information", {}).get(
            "total_missing_items", 0
        )
        checklist_items = _build_human_review_checklist(
            safety_valid=validation.safety_valid,
            schema_valid=validation.schema_valid,
            has_scorecard=scorecard is not None,
            has_bull_bear=bull_case_summary is not None
            and bear_case_summary is not None,
            has_risk=risk_summary is not None,
            has_citations=len(citations) > 0,
            missing_count=missing_count_val,
            is_mock=(report_provenance == "mock"),
            has_t1_t2=_has_t1_t2_evidence(source_tier, citations, primary_facts),
        )
        report_content["human_review_checklist"] = [
            item.model_dump() for item in checklist_items
        ]
        _workflow_status = report_content.get("workflow_status")
        if isinstance(_workflow_status, dict):
            _workflow_status["schema_valid"] = validation.schema_valid

        # Phase 32A Slice-1 hotfix — refresh the Phase-31 memo's EMBEDDED checklist
        # snapshot from the FINAL authoritative checklist above. The memo is built
        # (and safety-scanned) BEFORE validation, so its embedded snapshot would
        # otherwise be stale (e.g. still list the schema item as "Schema invalid"
        # after RC-6 flipped schema_valid true), contradicting the header. Only the
        # ``human_review_checklist`` sub-field is refreshed — deterministic checklist
        # labels/notes that are a strict SUBSET of the already-scanned content (no
        # new terms, no fabrication) — the memo prose is NOT rebuilt, so nothing
        # moves past the safety gate. Dark-safe: only runs when a memo exists (i.e.
        # SOURCE_RESEARCH_MEMO_ENABLED on). publication_ready / human_review_required
        # are untouched.
        _memo = report_content.get("research_memo")
        if isinstance(_memo, dict) and isinstance(
            _memo.get("human_review_checklist"), dict
        ):
            _memo["human_review_checklist"] = _memo_human_review_checklist_snapshot(
                report_content["human_review_checklist"]
            )

        schema_validation_for_save = validation.persisted_schema_json

        # Source summary — carries the compact LLM council metadata (Phase 28A)
        # so the report GET can surface it without a schema migration. When the
        # council is disabled this is an honest {"llm_used": False}.
        # Phase 29A: additive source-framework block. It records which external
        # source connectors are wired vs planned, and the planned-source gaps —
        # honest, recommendation-free metadata (never safety-scanned report body).
        _registry = build_registry()
        source_framework_summary = {
            "registry": _registry.summary(),
            "planned_source_gaps": registry_gap_messages(_registry),
            # Phase 29B: whether the connector layer fed evidence into the pack.
            "connector_layer_enabled": bool(settings.source_connector_enabled),
        }
        source_summary_for_save = {
            "total_sources": len(sources),
            "total_citations": len(citations),
            "source_types": list({s.source_type for s in sources}),
            "llm_council": council_result.to_metadata_dict(),
            "source_framework": source_framework_summary,
            # Phase 32A AD-2 — auditable report-level provenance (real / mock /
            # mixed / unknown). Stored in this flexible metadata dict, so no
            # schema/migration change is needed.
            "data_provenance": report_provenance,
        }

        # Phase 32A Slice 3 — resolve the report's lineage from EXPLICIT signals
        # only (public research entities). from-report / from-company read the
        # company + agent_run off the SOURCE report; from-workflow-state reads them
        # off the in-memory state; genuinely-unknown stays None (never fabricated,
        # never inferred from ticker/name). Used to own the final report + key its
        # persisted council citations to the company-pinned agent_run. OFF ⇒ None.
        lineage_company_id: uuid.UUID | None = None
        lineage_agent_run_id: uuid.UUID | None = None
        if settings.report_citation_persistence_enabled:
            if source_report is not None:
                lineage_company_id = source_report.company_id
                lineage_agent_run_id = source_report.created_by_agent_run_id
            else:
                lineage_company_id = _coerce_uuid(state.get("company_id"))
                lineage_agent_run_id = _coerce_uuid(state.get("agent_run_id"))

        saved_report = await _save_final_report_draft(
            db=db,
            report_content=report_content,
            safety_result=safety_result,
            schema_validation=schema_validation_for_save,
            source_summary=source_summary_for_save,
            scorecard_id=scorecard.id if scorecard else None,
            company_name=company_name,
            ticker=ticker,
            source_report_id=source_report.id if source_report else None,
            llm_used=council_result.llm_used,
            company_id=lineage_company_id,
            created_by_agent_run_id=lineage_agent_run_id,
            council_result=council_result,
        )

        sections_generated = list(report_content.keys())
        missing_sections = [s for s in _REQUIRED_SECTIONS if s not in report_content]

        # ``checklist_items`` was recomputed from the final validation flags above
        # (Phase 32A RC-6) and already persisted into ``report_content``; the same
        # objects are returned on the response so body and response agree.

        provisional_status = None
        if committee_chair_summary:
            provisional_status = committee_chair_summary.get(
                "provisional_internal_status"
            )
        if not provisional_status and scorecard:
            provisional_status = scorecard.internal_status
        if not provisional_status or provisional_status not in ALLOWED_INTERNAL_STATUSES:
            provisional_status = "not_enough_data"

        return FinalReportResponse(
            report_id=saved_report.id,
            status="draft",
            review_status="draft",
            schema_valid=validation.schema_valid,
            safety_valid=validation.safety_valid,
            human_review_required=True,
            research_complete=validation.research_complete,
            publication_ready=validation.publication_ready,
            internal_status=provisional_status,
            sections_generated=sections_generated,
            missing_sections=missing_sections,
            safety_validation=safety_result,
            schema_validation_errors=validation.schema_errors,
            schema_validation_warnings=validation.schema_warnings,
            validation_warnings=validation.validation_warnings,
            scorecard_id=scorecard.id if scorecard else None,
            source_count=len(sources),
            citation_count=len(citations),
            llm_used=council_result.llm_used,
            llm_provider=council_result.provider,
            llm_model=council_result.model,
            council_version=(
                council_result.council_version if council_result.llm_used else None
            ),
            council_agents_completed=council_result.agents_completed,
            council_agents_failed=council_result.agents_failed,
            council_agents_skipped=council_result.agents_skipped,
            evidence_pack_version=(
                council_result.evidence_pack_version if council_result.llm_used else None
            ),
            evidence_item_count=council_result.evidence_item_count,
            committee_label=council_result.committee_label,
            human_review_checklist=checklist_items,
        )
