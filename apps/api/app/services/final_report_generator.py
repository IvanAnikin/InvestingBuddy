async def _save_final_report_draft(
    db: AsyncSession,
    report_content: dict[str, Any],
    safety_result: SafetyValidationResult,
    schema_validation: dict[str, Any],
    source_summary: dict[str, Any],
    scorecard_id: uuid.UUID | None,
    company_name: str | None,
    ticker: str | None,
    source_report_id: uuid.UUID | None,
    llm_used: bool = False,
) -> Report:
    """
    Save the assembled final report as a new draft report record.

    Phase 28A.1 — the title honestly reflects whether the LLM analysis council
    ran ("LLM Council Analysis Draft" vs "Internal Analysis Draft"). It NEVER
    says "Phase 9" — this is the final-report-generator path, not the legacy
    deterministic Analysis Council draft. Legacy reports are identified by a
    NULL ``final_report_version``; every report saved here carries a version.
    """
    import json

    # Phase 28A.1 — honest, non-"Phase 9" title. The council-ran variant makes
    # the LLM involvement obvious in report lists without opening the report.
    kind_label = "LLM Council Analysis Draft" if llm_used else "Internal Analysis Draft"
    who = company_name or "Unknown"
    title_prefix = f"{kind_label} — {who}"
    if ticker:
        title_prefix = f"{kind_label} — {ticker} — {who}"

    slug = (
        f"final-report-{ticker or 'unknown'}-{uuid.uuid4().hex[:8]}"
        .lower()
        .replace(" ", "-")
    )

    # Build markdown summary for content_markdown
    content_lines = [
        "# INTERNAL ADMIN DRAFT — FINAL REPORT",
        "",
        "NOT INVESTMENT ADVICE. NOT A PUBLIC TRADING RECOMMENDATION. Human review required.",
        "",
        "---",
        "",
        "## Report Sections (Structured JSON — see safety_validation_json"
        " and schema_validation_json for validation status)",
        "",
        "```json",
        json.dumps(report_content, indent=2, default=str),
        "```",
    ]
    content_markdown = "\n".join(content_lines)

    schema_valid = schema_validation.get("is_valid", False)

    report = Report(
        id=uuid.uuid4(),
        title=title_prefix,
        slug=slug,
        report_type="company_deep_dive",
        status="draft",
        summary=(
            f"{kind_label} for {company_name or 'Unknown'}. "
            f"LLM council: {'used' if llm_used else 'not used'}. "
            f"Safety: {'PASSED' if safety_result.passed else 'FAILED'}. "
            f"Schema: {'valid' if schema_valid else 'invalid'}. "
            f"Human review required."
        ),
        content_markdown=content_markdown,
        review_status="draft",
        human_review_required=True,
        final_report_version=FINAL_REPORT_VERSION,
        safety_validation_json=safety_result.model_dump(),
        schema_validation_json=schema_validation,
        source_summary_json=source_summary,
        scorecard_id=scorecard_id,
    )

    db.add(report)
    await db.flush()
    # Persist the draft. get_db() does not commit for us (it yields the session
    # and closes it, which rolls back an uncommitted transaction), so every
    # write service commits its own work — this one must too, or the generated
    # final-report draft (and its final_report_version / validation JSON) is
    # silently discarded when the request ends.
    await db.commit()
    await db.refresh(report)
    return report


